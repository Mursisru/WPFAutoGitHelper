                ["ja"] = Merge(en, CreateJa()),
                ["ko"] = Merge(en, CreateKo()),
                ["cs"] = Merge(en, CreateCs()),
            };
        }

        private static Dictionary<string, string> Merge(
            Dictionary<string, string> bas,
            Dictionary<string, string> over)
        {
            var d = new Dictionary<string, string>(bas);
            foreach (var kv in over)
                d[kv.Key] = kv.Value;
            return d;
        }

